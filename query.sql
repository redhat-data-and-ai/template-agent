SELECT 
    e.EMPLOYEE_FULL_NAME as employee_name,
    m.EMPLOYEE_FULL_NAME as manager_name,
    m.EMAIL_ADDRESS as manager_email
FROM PEOPLEANALYTICS_DB.CALC_MARTS.WRKD_EMPLOYEE_HIERARCHY e
LEFT JOIN PEOPLEANALYTICS_DB.CALC_MARTS.WRKD_EMPLOYEE_HIERARCHY m 
    ON e.SUPER_ID = m.EMPLOYEE_NUMBER
WHERE e.EMAIL_ADDRESS = 'imrankha@redhat.com'
  AND e.SUPER_END_DATE = '9999-12-31'
  AND m.SUPER_END_DATE = '9999-12-31'
LIMIT 1;
