"""Render deployment overlays from `config/agent/deployment/values.yaml`.

These templates are config-driven: building an agent means editing
`config/`, not code. Deployment was the hole in that. Changing a replica
count or a memory limit meant editing a kustomization patch — which is
code, and which drifted from `values.yaml` the moment anyone did it.
At the time this was written the two disagreed on three values
(maxReplicas 8 vs 10, memory target 80 vs 75, agent memory limit 1Gi vs
2Gi), and nothing noticed.

So `values.yaml` becomes the source of truth and this renders the
patches from it. Not Helm: `agent-engine` deploys every agent by
downloading this repo's kustomize overlay and patching it, so the output
has to stay a kustomize overlay.

    make render-deployment          # write
    make render-deployment-check    # fail if out of date (CI)

Two things per target are generated. `generated.yaml` is written whole
and must not be hand-edited. The `components:` list in
`kustomization.yaml` is rewritten in place; everything else in that file
is left byte-for-byte alone, because the structural parts of an overlay
are genuinely hand-written.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
VALUES = REPO_ROOT / "config" / "agent" / "deployment" / "values.yaml"

# Logical name in values.yaml -> path from an overlay directory.
COMPONENT_PATHS = {
    "postgres": "../../components/postgres",
    "redis": "../../components/redis",
    "opa": "../../components/opa",
    "evalRunner": "../../components/eval-runner",
    "scaleToZero": "../../components/scale-to-zero",
    "externalChannels": "../../components/external-channels",
    "documentsPvc": "../../components/documents-pvc",
    "configPvc": "../../components/config-pvc",
}

BANNER = (
    "# Generated by scripts/render_deployment.py — DO NOT EDIT.\n"
    "# Source: config/agent/deployment/values.yaml\n"
    "# Regenerate with `make render-deployment`.\n"
)

GENERATED_FILE = "generated.yaml"


def _merge(base: dict[str, Any], override: dict[str, Any]) -> dict[str, Any]:
    """Deep-merge an override tree over a base tree."""
    out = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _merge(out[key], value)
        else:
            out[key] = value
    return out


def for_target(values: dict[str, Any], target: str) -> dict[str, Any]:
    """Values as they apply to one overlay.

    `targets:` is the escape hatch for real environment differences —
    Kind cannot schedule the eval-runner, for instance. Without it a
    single shared file would force every overlay to be identical, and
    people would go back to editing patches by hand.
    """
    overrides = (values.get("targets") or {}).get(target) or {}
    merged = _merge(values, overrides)
    merged.pop("targets", None)
    return merged


def _get(values: dict[str, Any], path: str, default: Any = None) -> Any:
    """Read a dotted path out of the values tree."""
    node: Any = values
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            return default
        node = node[part]
    return node


def _resources(block: dict[str, Any]) -> dict[str, Any]:
    """A container resources block, omitting anything values.yaml leaves out."""
    out: dict[str, Any] = {}
    for kind in ("requests", "limits"):
        fields = {
            field: str(value)
            for field, value in (block.get(kind) or {}).items()
            if field in ("memory", "cpu")
        }
        if fields:
            out[kind] = fields
    return out


def _probes(probes: dict[str, Any]) -> dict[str, Any]:
    """The three probes, as strategic-merge fragments."""
    out: dict[str, Any] = {}
    for probe, key in (
        ("liveness", "livenessProbe"),
        ("readiness", "readinessProbe"),
        ("startup", "startupProbe"),
    ):
        spec = dict(probes.get(probe) or {})
        if not spec:
            continue
        fragment: dict[str, Any] = {}
        if "path" in spec:
            fragment["httpGet"] = {"path": spec.pop("path")}
        for field in (
            "initialDelaySeconds",
            "periodSeconds",
            "timeoutSeconds",
            "failureThreshold",
        ):
            if field in spec:
                fragment[field] = spec[field]
        out[key] = fragment
    return out


def _pod_labels(values: dict[str, Any]) -> dict[str, str]:
    """The recommended Kubernetes labels, for the pod template.

    Not the `app`/`component` pair already on the Deployment: those are
    the selector, and a selector cannot be changed on a live workload.
    These go on the pod template only, which is where log and metric
    collectors read service identity from.

    `version` is the one that earns its place. Without it a metrics
    backend cannot split a series by release, so "did the rollout cause
    this" is answered by eye against a deploy timestamp.
    """
    labels = {
        "app.kubernetes.io/name": _get(values, "app.serviceName")
        or _get(values, "app.name", "agent"),
        "app.kubernetes.io/component": _get(values, "app.component", "agent"),
        "app.kubernetes.io/version": str(_get(values, "image.tag", "latest")),
        "app.kubernetes.io/part-of": _get(values, "app.partOf"),
        "app.kubernetes.io/managed-by": "kustomize",
    }
    return {k: str(v) for k, v in labels.items() if v}


def _rollout(values: dict[str, Any]) -> dict[str, Any]:
    """Deployment-level rollout fields from the `rollout:` block."""
    rollout = _get(values, "rollout", {}) or {}
    spec: dict[str, Any] = {}

    surge = rollout.get("maxSurge")
    unavailable = rollout.get("maxUnavailable")
    if surge is not None or unavailable is not None:
        rolling: dict[str, Any] = {}
        if surge is not None:
            rolling["maxSurge"] = surge
        if unavailable is not None:
            rolling["maxUnavailable"] = unavailable
        spec["strategy"] = {"type": "RollingUpdate", "rollingUpdate": rolling}

    for field in ("minReadySeconds", "progressDeadlineSeconds"):
        if rollout.get(field) is not None:
            spec[field] = int(rollout[field])
    return spec


def _agent_patch(values: dict[str, Any]) -> dict[str, Any] | None:
    """Replicas, resources and probes on the agent Deployment.

    Containers merge by name, so `name: agent` is load-bearing — without
    it strategic merge appends a second container rather than editing the
    one that is there.
    """
    container: dict[str, Any] = {"name": "agent"}

    resources = _resources(_get(values, "resources", {}) or {})
    if resources:
        container["resources"] = resources
    container.update(_probes(_get(values, "probes", {}) or {}))

    drain = _get(values, "drain", {}) or {}
    pod_spec: dict[str, Any] = {}
    grace = drain.get("terminationGracePeriodSeconds")
    if grace is not None:
        pod_spec["terminationGracePeriodSeconds"] = int(grace)
    delay = drain.get("preStopSleepSeconds")
    if delay is not None:
        # Endpoint removal and the TERM signal race. Kubernetes sends
        # both at once, and a pod that begins shutting down before the
        # router has stopped sending it traffic drops the requests
        # arriving in between. Sleeping in preStop holds the container
        # open while the removal propagates; shutdown starts after.
        container["lifecycle"] = {
            "preStop": {"exec": {"command": ["sleep", str(int(delay))]}}
        }

    spec: dict[str, Any] = _rollout(values)
    replicas = _get(values, "app.replicas")
    if replicas is not None and not _get(values, "components.scaleToZero", False):
        # Patches apply after components, so a replica count here would
        # overwrite the 0 that scale-to-zero exists to set.
        spec["replicas"] = int(replicas)
    if len(container) > 1:
        pod_spec["containers"] = [container]

    template: dict[str, Any] = {}
    labels = _pod_labels(values)
    if labels:
        template["metadata"] = {"labels": labels}
    if pod_spec:
        template["spec"] = pod_spec
    if template:
        spec["template"] = template

    if not spec:
        return None
    return {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": "agent"},
        "spec": spec,
    }


def _hpa_patch(values: dict[str, Any]) -> dict[str, Any] | None:
    """HPA bounds and targets.

    Skipped when autoscaling is off: the overlay drops the HPA in that
    case, and a patch with no target is an error, not a no-op.
    """
    autoscaling = _get(values, "autoscaling", {}) or {}
    if not autoscaling.get("enabled", False):
        return None
    if _get(values, "components.scaleToZero", False):
        # The scale-to-zero component deletes the HPA — a ScaledObject and
        # an HPA would fight over the same Deployment. Patching a resource
        # that component removed fails the whole render.
        return None

    spec: dict[str, Any] = {}
    if "minReplicas" in autoscaling:
        spec["minReplicas"] = int(autoscaling["minReplicas"])
    if "maxReplicas" in autoscaling:
        spec["maxReplicas"] = int(autoscaling["maxReplicas"])

    # metrics is a list, so strategic merge replaces it wholesale rather
    # than merging element-wise. Emit the complete list or not at all.
    #
    # Each target is optional and omitting one drops that metric. That
    # matters for memory: the HPA acts on the *highest* recommendation
    # across its metrics, so a target on a signal that does not track
    # load does not sit harmlessly alongside the others — it overrides
    # them. Memory here is a static footprint, resident before the
    # first request, and a target on it held the fleet at maxReplicas
    # permanently.
    metrics: list[dict[str, Any]] = []
    for name, target in (
        ("cpu", autoscaling.get("targetCPUUtilizationPercentage")),
        ("memory", autoscaling.get("targetMemoryUtilizationPercentage")),
    ):
        if target is None:
            continue
        metrics.append(
            {
                "type": "Resource",
                "resource": {
                    "name": name,
                    "target": {
                        "type": "Utilization",
                        "averageUtilization": int(target),
                    },
                },
            }
        )

    in_flight = autoscaling.get("targetRunsInFlightPerPod")
    if in_flight is not None:
        # The metric that actually tracks saturation. An agent turn
        # waits on a model for almost all of its wall-clock time, so a
        # pod can hold a hundred concurrent runs at fifteen percent
        # CPU — neither resource metric crosses its target under the
        # load that exhausts the connection pools and the event loop.
        # Published by deep_agent/aegra/inflight_metrics.py.
        metrics.append(
            {
                "type": "Pods",
                "pods": {
                    # The per-pod gauge, not the cluster-wide one.
                    # A `Pods` metric averages across replicas, and
                    # every replica reports the same cluster total,
                    # so the average never fell as pods were added
                    # and the HPA ratcheted to maxReplicas.
                    "metric": {"name": "aegra_runs_in_flight_pod"},
                    "target": {
                        "type": "AverageValue",
                        "averageValue": str(in_flight),
                    },
                },
            }
        )

    if metrics:
        spec["metrics"] = metrics

    scale_down = autoscaling.get("scaleDown") or {}
    window = scale_down.get("stabilizationWindowSeconds")
    if window is not None:
        behavior: dict[str, Any] = {
            "scaleDown": {"stabilizationWindowSeconds": int(window)}
        }
        percent = scale_down.get("percentPerMinute")
        if percent is not None:
            # Retire pods slowly. Every pod removed is a set of runs
            # that must drain or be resumed elsewhere, so a burst of
            # scale-down during a lull is how long-running work gets
            # interrupted for no reason.
            behavior["scaleDown"]["policies"] = [
                {"type": "Percent", "value": int(percent), "periodSeconds": 60}
            ]
            behavior["scaleDown"]["selectPolicy"] = "Min"
        spec["behavior"] = behavior

    if not spec:
        return None
    return {
        "apiVersion": "autoscaling/v2",
        "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": "agent"},
        "spec": spec,
    }


def _buildconfig_patch(values: dict[str, Any]) -> dict[str, Any] | None:
    resources = _resources(_get(values, "build.resources", {}) or {})
    if not resources:
        return None
    return {
        "apiVersion": "build.openshift.io/v1",
        "kind": "BuildConfig",
        "metadata": {"name": "agent"},
        "spec": {"resources": resources},
    }


def _service_patch(values: dict[str, Any]) -> dict[str, Any] | None:
    service = _get(values, "networking.service", {}) or {}
    spec: dict[str, Any] = {}
    if service.get("type"):
        spec["type"] = str(service["type"])
    port = service.get("port")
    if port is not None:
        # Same list-replacement rule as the HPA metrics above.
        spec["ports"] = [
            {
                "name": "http",
                "port": int(port),
                "targetPort": int(port),
                "protocol": "TCP",
            }
        ]
    if not spec:
        return None
    return {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": "agent"},
        "spec": spec,
    }


def _route_patch(values: dict[str, Any]) -> dict[str, Any] | None:
    route = _get(values, "networking.route", {}) or {}
    if not route.get("enabled", False):
        return None
    tls = {k: str(v) for k, v in (route.get("tls") or {}).items()}
    if not tls:
        return None
    return {
        "apiVersion": "route.openshift.io/v1",
        "kind": "Route",
        "metadata": {"name": "agent"},
        "spec": {"tls": tls},
    }


# Patches that only make sense where the resource exists. The kind overlay
# has no BuildConfig, Route or HPA, so rendering them there would break
# `kubectl kustomize`.
BUILDERS = {
    "openshift": (
        _agent_patch,
        _hpa_patch,
        _buildconfig_patch,
        _service_patch,
        _route_patch,
    ),
    "kind": (_agent_patch, _service_patch),
}


def render_patches(values: dict[str, Any], target: str) -> str:
    """An overlay's generated.yaml: one strategic-merge doc per resource."""
    patches = [p for build in BUILDERS[target] if (p := build(values)) is not None]
    body = yaml.safe_dump_all(patches, sort_keys=False, default_flow_style=False)
    return BANNER + body


def render_components(values: dict[str, Any]) -> str:
    """The `components:` block, rebuilt from the toggles in values.yaml."""
    toggles = _get(values, "components", {}) or {}
    lines = ["components:"]
    for name, path in COMPONENT_PATHS.items():
        if toggles.get(name, False):
            lines.append(f"  - {path}")
        else:
            lines.append(f"  # {name}: disabled in values.yaml")
    # Trailing blank line: the block sits between other top-level keys and
    # the regex that replaces it consumes the separator.
    return "\n".join(lines) + "\n\n"


_COMPONENTS_BLOCK = re.compile(r"^components:\n(?:(?:[ \t]+\S.*)?\n)*", re.MULTILINE)


def rewrite_components(kustomization: str, block: str) -> str:
    """Swap the components block, leaving the rest of the file untouched.

    A YAML round-trip would be cleaner in principle and worse in practice:
    it drops the comments that explain why a component is excluded, and
    those comments are the most useful thing in the file.
    """
    if not _COMPONENTS_BLOCK.search(kustomization):
        raise SystemExit(
            "no `components:` block found; add one (even empty) before rendering"
        )
    return _COMPONENTS_BLOCK.sub(block, kustomization, count=1)


def ensure_patch_reference(kustomization: str) -> str:
    """Make sure the overlay actually applies generated.yaml."""
    if f"path: {GENERATED_FILE}" in kustomization:
        return kustomization
    if re.search(r"^patches:$", kustomization, re.MULTILINE):
        return re.sub(
            r"^patches:$",
            f"patches:\n  - path: {GENERATED_FILE}",
            kustomization,
            count=1,
            flags=re.MULTILINE,
        )
    return kustomization.rstrip("\n") + f"\n\npatches:\n  - path: {GENERATED_FILE}\n"


TUNING_CONFIGMAP = REPO_ROOT / "deployment" / "base" / "configmap-tuning.yaml"


def render_tuning_configmap(values: dict[str, Any]) -> str:
    """The capacity ConfigMap, generated from the `tuning:` block.

    Kept out of `agent-config` so it can be consumed with `envFrom`.
    The agent container lists agent-config keys one at a time on
    purpose — an unlisted key must not reach the pod — but applying
    that to a dozen related bounds is a hundred lines of boilerplate
    in which one missed entry silently restores a library default.
    Everything here is a pool bound or a timeout.

    Generated rather than hand-written because a tuning value that
    disagrees between values.yaml and the manifest is a value nobody
    can reason about, and the whole point of these numbers is that
    they are reasoned about together.
    """
    tuning = _get(values, "tuning", {}) or {}
    body = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "agent-tuning",
            "labels": {"app": "agent", "component": "agent"},
        },
        "data": {k: str(v) for k, v in tuning.items()},
    }
    header = (
        "# Generated by scripts/render_deployment.py from the\n"
        "# `tuning:` block of config/agent/deployment/values.yaml.\n"
        "# Do not edit; run `make render-deployment`.\n"
        "#\n"
        "# These are pool bounds and timeouts. Each multiplies by the\n"
        "# pod count and shares the server's max_connections with\n"
        "# everything else on that database, so they are set together,\n"
        "# not individually. The arithmetic is in docs/scalability.md.\n"
    )
    return header + yaml.safe_dump(body, sort_keys=False, default_flow_style=False)


def plan(values: dict[str, Any]) -> dict[Path, str]:
    """Every file this would write, mapped to its intended contents."""
    out: dict[Path, str] = {}
    out[TUNING_CONFIGMAP] = render_tuning_configmap(values)
    for target in BUILDERS:
        overlay = REPO_ROOT / "deployment" / "overlays" / target
        if not overlay.is_dir():
            continue

        resolved = for_target(values, target)
        out[overlay / GENERATED_FILE] = render_patches(resolved, target)

        kustomization = overlay / "kustomization.yaml"
        text = kustomization.read_text()
        text = rewrite_components(text, render_components(resolved))
        text = ensure_patch_reference(text)
        out[kustomization] = text
    return out


def main() -> int:
    """Render the deployment from values.yaml. Returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any file is out of date; write nothing",
    )
    args = parser.parse_args()

    values = yaml.safe_load(VALUES.read_text()) or {}
    wanted = plan(values)

    stale = [
        p for p, text in wanted.items() if not p.is_file() or p.read_text() != text
    ]

    if args.check:
        if stale:
            print("Deployment overlays are out of date:")
            for path in stale:
                print(f"  {path.relative_to(REPO_ROOT)}")
            print("\nRun `make render-deployment`.")
            return 1
        print("Deployment overlays are up to date.")
        return 0

    for path, text in wanted.items():
        path.write_text(text)
    if stale:
        print(f"Rendered {len(stale)} file(s) from {VALUES.relative_to(REPO_ROOT)}:")
        for path in stale:
            print(f"  {path.relative_to(REPO_ROOT)}")
    else:
        print("Already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
